# hard function up to 3 loops from https://arxiv.org/pdf/1004.3653

using Distributed
include("..\\strong coupling\\constants.jl")



# eqn 7.4
@everywhere function H1_func(L,nf) 

    H1 = CF * (-L^2 + 3*L - 8 + z2)

    return H1
end

# eqn 7.5
@everywhere function H2_func(L,nf)

    H2 = (
        CF^2 * (
              (1/2)*L^4 
            - 3*L^3 
            + (25/2 - z2)*L^2 
            + (-(45/2) + 24*z3 - 9*z2)*L 
            + 255/8 - 30*z3 + 21*z2 - (83/10)*z2^2
        ) 
        + CF*CA * (
              (11/9)*L^3 
            + (-233/18 + 2*z2)*L^2 
            + (2545/54 - 26*z3 + (22/3)*z2)*L 
            - 51157/648 + (313/9)*z3 - (337/18)*z2 + (44/5)*z2^2
        ) 
        + CF*nf * (
              (-2/9)*L^3 
            + (19/9)*L^2 
            + (-209/27 - (4/3)*z2)*L 
            + 4085/324 + (2/9)*z3 + (23/9)*z2
        )
    )

    return H2
end

# eqn 7.8
@everywhere function H3_func(L,nf) 

    H3 = (
        CF^3 * (
            - 1/6*L^6 
            + 3/2*L^5 
            + (-17/2 + 1/2*z2)*L^4 
            + (9*z2 + 27 - 24*z3)*L^3 
            + (102*z3 - 507/8 - 105/2*z2 + 83/10*z2^2)*L^2 
            + (-214*z3 - 240*z5 - 8*z3*z2 + 357/2*z2 + 207/10*z2^2 + 785/8)*L 
            - 413/5*z2^2 + 664*z5 - 6451/24*z2 + 37729/630*z2^3 - 470*z3 + 250*z2*z3 - 2539/12 + 16*z3^2
            ) 
        + CF^2*CA * ( 
            - 11/9*L^5 
            + (299/18 - 2*z2)*L^4 
            + (-2585/27 + 26*z3 - 1/9*z2)*L^3 
            + (206317/648 - 1807/9*z3 + 502/9*z2 - 34/5*z2^2)*L^2 
            + (-13805/24 + 120*z5 + 2441/3*z3 - 11260/27*z2 - 10*z3*z2 + 162/5*z2^2)*L 
            + 415025/648 - 2756/9*z5 - 18770/27*z3 + 296/3*z3^2 + 538835/648*z2 - 3751/9*z2*z3 - 4943/270*z2^2 - 12676/315*z2^3
        )
        + CF^2*nf * (
            (2/9)*L^5 
            - (25/9)*L^4 
            + (410/27 + 10/9*z2)*L^3 
            + (-12815/324 + 70/9*z3 - 112/9*z2)*L^2 
            + (3121/108 - 610/9*z3 + 1618/27*z2 + 28/5*z2^2)*L 
            + 41077/972 - 416/9*z5 + 13184/81*z3 - 31729/324*z2 - 38/9*z2*z3 - 331/27*z2^2
        )
        + CF*CA^2 * (
            - 121/54*L^4 
            + (2869/81 - 44/9*z2)*L^3 
            + (-18682/81 + 88*z3 + 26/9*z2 - 44/5*z2^2)*L^2 
            + (1045955/1458 + 136*z5 - 17464/27*z3 + 17366/81*z2 + 88/3*z2*z3 - 94/3*z2^2)*L 
            - 51082685/52488 - 434/9*z5 + 505087/486*z3 - 1136/9*z3^2 - 412315/729*z2 + 416/3*z2*z3 + 22157/270*z2^2 - 6152/189*z2^3
        ) 
        + CF*CA*nf * (
              22/27*L^4 
            + (-974/81 + 8/9*z2)*L^3 
            + (5876/81 - 8*z3 + 16/3*z2)*L^2 
            + (-154919/729 + 724/9*z3 - 5864/81*z2 + 44/15*z2^2)*L
            + 1700171/6561 - 4/3*z5 - 4288/27*z3 + 115555/729*z2 + 4/3*z2*z3 + 2/27*z2^2
        )
        + CF*nf^2 * (
            - 2/27*L^4 
            + 76/81*L^3 
            + (-406/81 - 8/9*z2)*L^2 
            + (9838/729 + 16/27*z3 + 152/27*z2)*L 
            - 190931/13122 - 416/243*z3 - 824/81*z2 - 188/135*z2^2
        ) 
    )

    return H3
end

@everywhere function H_func(; μH::Float64, Q::Float64, αs::Float64, order::Int64, nf::Int64)

    L = log(Q^2/μH^2)

    H1 = H1_func(L,nf)
    H2 = H2_func(L,nf)
    H3 = H3_func(L,nf)

    if order == 1 
        total = 1 + (αs/4π)*H1
    end
    if order == 2  
        total = 1 + (αs/4π)*H1 + (αs/4π)^2*H2
    end
    if order == 3 
        total = 1 + (αs/4π)*H1 + (αs/4π)^2*H2 + (αs/4π)^3*H3
    end

    return total

end