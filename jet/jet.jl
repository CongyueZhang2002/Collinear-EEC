@everywhere function J_func(; b::Float64, μJ::Float64, νdQ::Float64, αs::Float64, order::Int64, nf::Int64)

    Lb = log((b*μJ/b0)^2)
    LQ = log(νdQ)

    J1 = J1_func(αs,Lb,LQ,nf)
    J2 = J2_func(αs,Lb,LQ,nf)
    J3 = J3_func(αs,Lb,LQ,nf)

    if order == 1 
        total = J1
    end
    if order == 2  
        total = J1 + J2
    end
    if order == 3 
        total = J1 + J2 + J3
    end

    return total

end
