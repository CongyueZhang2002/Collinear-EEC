    if order == 0
        Jq = 1 + as*(qL1*Lz) + as^2*(Lz^2*qL2) + as^3*(Lz^3*qL3) + as^4*(Lz^4*qL4) + as^5*(Lz^5*qL5) + as^6*(Lz^6*qL6) + as^7*(Lz^7*qL7) + as^8*(Lz^8*qL8) + as^9*(Lz^9*qL9)
