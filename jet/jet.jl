@everywhere function J1_func(αs,Lb,LQ,nf)

    J1 = (
        1 + (CF*αs)/π + (3*CF*Lb*αs)/(4*π) + 
        (CF*Lb*LQ*αs)/π - (CF*π*αs)/3
    )

    return J1
end

